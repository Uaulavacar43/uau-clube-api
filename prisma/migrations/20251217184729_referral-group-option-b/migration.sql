-- 5) FK CashbackTransaction -> ReferralGroup (SET NULL)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE c.conname = 'CashbackTransaction_referralGroupId_fkey'
      AND n.nspname = 'public'
      AND t.relname = 'CashbackTransaction'
  ) THEN
    ALTER TABLE "public"."CashbackTransaction"
      ADD CONSTRAINT "CashbackTransaction_referralGroupId_fkey"
      FOREIGN KEY ("referralGroupId") REFERENCES "public"."ReferralGroup"("id")
      ON DELETE SET NULL ON UPDATE CASCADE;
  END IF;
END $$;

