-- FKs (sem IF NOT EXISTS -> usamos DO/pg_constraint)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE c.conname = 'ReferralGroupMember_groupId_fkey'
      AND n.nspname = 'public'
      AND t.relname = 'ReferralGroupMember'
  ) THEN
    ALTER TABLE "public"."ReferralGroupMember"
      ADD CONSTRAINT "ReferralGroupMember_groupId_fkey"
      FOREIGN KEY ("groupId") REFERENCES "public"."ReferralGroup"("id")
      ON DELETE RESTRICT ON UPDATE CASCADE;
  END IF;
END $$;

